// Generates the push service worker's API config from the Angular single source of truth.
//
// The service worker (public/push/sw-push.js) is a STATIC asset — it can't import the Angular `apiPrefix`
// constant at runtime, and hardcoding `/api/v1` in two places drifts when the version bumps. This script
// reads `API_PREFIX` from src/app/services/constants.ts and emits public/push/sw-config.js, which sw-push.js
// loads via `importScripts('./sw-config.js')`. npm runs it automatically as `prebuild` before every
// `ng build`, so the SW always mirrors the app's apiPrefix. Commit the generated file (deterministic) so a
// fresh checkout is self-consistent; prebuild keeps it fresh whenever API_PREFIX changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const constantsPath = join(root, 'src/app/services/constants.ts');
const outPath = join(root, 'public/push/sw-config.js');

const src = readFileSync(constantsPath, 'utf8');
const m = src.match(/export\s+const\s+API_PREFIX\s*=\s*(['"])([^'"]+)\1/);
if (!m) {
  // Fail loud: a silent skip would leave the SW reading a stale/missing config. If you renamed or moved
  // API_PREFIX, update this regex to match the new declaration.
  throw new Error(
    `[gen-sw-config] could not find 'export const API_PREFIX = "..."' in ${constantsPath}`,
  );
}
const prefix = m[2];

const body = `// AUTO-GENERATED by scripts/gen-sw-config.mjs from src/app/services/constants.ts (API_PREFIX).
// The push service worker loads this via importScripts so its endpoint stays in lockstep with the
// Angular apiPrefix — do NOT edit by hand; \`npm run prebuild\` regenerates it before every build.
self.__SOMS_API_PREFIX__ = ${JSON.stringify(prefix)};
`;
writeFileSync(outPath, body);
console.log(`[gen-sw-config] wrote ${outPath} (API_PREFIX=${JSON.stringify(prefix)})`);
