  adminTwoFactorEnabled?: boolean | null;
  /** Present even when the associated admin access is disabled. */
  adminRole?: AdminRole | null;
  id: number;
  account: string;
  /** Namespace 0 is the local namespace; other values are federated guests. */
  namespaceId: number;
  createdAt: number;
  updatedAt: number;
