// Federation v1 bidirectional recognition lifecycle.
export type FederationTrustLevel =
  | 'unrecognized'
  | 'establishing'
  | 'available'
  | 'degraded'
  | 'halted';

export interface FederatedPeer {
  domain: string;
  trustLevel: FederationTrustLevel;
  addedBy: string | null;
  createdAt: number;
  trustedAt: number | null; // start of the current trust epoch
  lastSuccessAt: number | null; // last successful signed S2S op (liveness watermark, ±60s)
  degradedAt: number | null; // last available→degraded transition
  degradationReason: string | null; // latest failure message
  degradationCount: number; // how many times degraded — flakiness signal
  haltedAt: number | null;
  haltCode: number | null;
  haltReason: string | null;
  resetInProgress: boolean;
  recognizesPeer: boolean;
  outboundRecognitionConfirmed: boolean;
  inboundRecognitionConfirmed: boolean;
  lightweightInboundReady: boolean;
  localServiceAvailable: boolean;
  remoteServiceReachable: boolean;
}

export interface FederatedPeerListResult {
  list: FederatedPeer[];
  total: number;
}

// ─── Federated peer daily quotas (POST /admin/quota/nodes) ───
export type QuotaCategory = 'messages' | 'files' | 'requests';

/** Per-entity override set (null/absent = use the global default). */
export interface QuotaOverrides {
  dailyMsgLimit?: number | null;
  dailyRequestLimit?: number | null;
  dailyFileLimit?: number | null;
  dailyFileBytesLimit?: number | null;
}

/** Today's usage for one category (count against the effective limit). */
export interface QuotaCategoryUsage {
  count: number;
  limit: number;
}

/** One federated peer's quota state. */
export interface QuotaNode {
  domain: string;
  trustLevel: FederationTrustLevel;
  overrides: QuotaOverrides;
  usage: Record<QuotaCategory, QuotaCategoryUsage> | undefined;
}

/** One entity's circuit-breaker snapshot (msg cnt / file cnt / file total size). `fileBytes.bytes` is a
 *  decimal string because file-total-size is a backend bigint that can exceed JS safe-integer range. */
export interface BreakerStatus {
  entity: string;
  scope: 'peer' | 'user';
  tripped: boolean;
  trippedDims: Array<'msg' | 'file' | 'fileBytes'>;
  retryAfter: number;
  msg: { count: number; limit: number };
  file: { count: number; limit: number };
  fileBytes: { bytes: string; limit: number };
}

/** All currently-tripped breakers (POST /admin/quota/breakers). */
export interface Breakers {
  peers: BreakerStatus[];
  users: BreakerStatus[];
}

/** Additive daily quota bump for the "continue" action (bytes, before the backend BigInt conversion). */
export interface ContinueQuotaInput {
  addMsg?: number;
  addFile?: number;
  addFileBytes?: number;
}

