import { Logger } from '@nestjs/common';
import { createHash, randomBytes } from 'node:crypto';
import { constants } from 'node:fs';
import {
  copyFile,
  link,
  lstat,
  mkdir,
  open,
  unlink,
  writeFile,
} from 'node:fs/promises';
import { basename, dirname, join } from 'node:path';

const logger = new Logger('CasStorage');
export type CasPublication = 'landed' | 'dedup';

async function syncPath(path: string): Promise<void> {
  const handle = await open(path, 'r');
  try {
    await handle.sync();
  } finally {
    await handle.close();
  }
}

/**
 * Publish a complete temporary inode without replacing a concurrent publisher's target.
 * Hard linking supplies atomic no-replace semantics that ordinary POSIX rename lacks.
 * The temporary directory must be on the destination filesystem. Failed attempts retain
 * their temporary copies for inspection; the caller always retains its source file.
 */
async function publishCopy(
  target: string,
  temporaryDirectory: string,
  prepare: (temporary: string) => Promise<void>,
): Promise<CasPublication> {
  const temporary = join(
    temporaryDirectory,
    `${basename(target)}.${process.pid}.${randomBytes(6).toString('hex')}.tmp`,
  );
  try {
    await mkdir(dirname(target), { recursive: true });
    await mkdir(temporaryDirectory, { recursive: true });
    await prepare(temporary);
    const source = await lstat(temporary);
    if (!source.isFile())
      throw new Error('CAS publication source is not a regular file');
    await syncPath(temporary);
    let outcome: CasPublication = 'landed';
    try {
      await link(temporary, target);
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error;
      const existing = await lstat(target);
      if (!existing.isFile() || existing.size !== source.size) {
        throw new Error('existing CAS target is not a complete regular file', {
          cause: error,
        });
      }
      logger.warn(
        `CAS target already exists; retaining published file: ${target}`,
      );
      outcome = 'dedup';
    }
    await syncPath(dirname(target));
    await unlink(temporary);
    await syncPath(temporaryDirectory);
    return outcome;
  } catch (error) {
    logger.error(`CAS publication failed for ${target}`, error);
    throw error;
  }
}

/** Copy first; never consume the resumable source before its owning task commits. */
export function publishContentAddressedFile(
  source: string,
  target: string,
  temporaryDirectory: string,
): Promise<CasPublication> {
  return publishCopy(target, temporaryDirectory, async (temporary) => {
    const entry = await lstat(source);
    if (!entry.isFile())
      throw new Error('CAS publication source is not a regular file');
    await copyFile(source, temporary, constants.COPYFILE_EXCL);
  });
}

/** Server-generated bytes use the same immutable publication boundary as transfers. */
export async function saveContentAddressedBuffer(
  bytes: Buffer,
  destination: (digest: string) => string,
  temporaryDirectory: string,
): Promise<string> {
  const digest = createHash('sha256').update(bytes).digest('hex');
  await publishCopy(destination(digest), temporaryDirectory, (temporary) =>
    writeFile(temporary, bytes, { flag: 'wx' }),
  );
  return digest;
}
