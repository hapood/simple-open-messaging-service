import { requireEnv } from '../common/env.js';
import { isValidSomfpDomain } from '../common/account.js';

/**
 * Federation (S2S) configuration. Loaded from env at module-init time (fail-fast via requireEnv).
 */
export interface FederationRuntimeConfig {
  /** dev-only: allow plain http:// for localhost federation testing (never in production). */
  allowInsecureHttp: boolean;
  forwardedResourcePolicy: 'trust' | 'rebuild';
  signingKey: SigningKeyLifecycleConfig;
  rootKey: RootKeyLifecycleConfig;
  peerKeyRefreshPollMs: number;
}

/** Startup configuration including the one-time identity input. */
export interface FederationConfig extends FederationRuntimeConfig {
  /** Startup-only identity input. Runtime callers must use KeypairService. */
  domain: string;
}

/**
 * Local signing-key rotation timings. All values are milliseconds and deployment-local: they shape
 * certificate validity intervals and the local switch schedule, and are never advertised to peers.
 * Receivers keep evaluating the exact half-open interval [notBefore, notAfter).
 */
export interface SigningKeyLifecycleConfig {
  /** Finite certificate lifetime from generation (default 30 days). */
  lifetimeMs: number;
  /** Maximum assumed absolute UTC clock difference between this server and peers (default 10 min).
   *  A successor's notBefore must lead the planned switch by at least this budget. */
  clockSkewBudgetMs: number;
  /** How long a successor is published before the planned switch (default 24 h). */
  successorPrepublicationMs: number;
  /** How long a predecessor stays published and valid after the switch (default 24 h). */
  predecessorRetentionMs: number;
}

export const DEFAULT_SIGNING_KEY_LIFETIME_MS = 30 * 24 * 3_600_000;
export const DEFAULT_CLOCK_SKEW_BUDGET_MS = 10 * 60_000;
export const DEFAULT_SUCCESSOR_PREPUBLICATION_MS = 24 * 3_600_000;
export const DEFAULT_PREDECESSOR_RETENTION_MS = 24 * 3_600_000;
export const DEFAULT_PEER_KEY_REFRESH_POLL_MS = 60_000;
export const MIN_PEER_KEY_REFRESH_POLL_MS = 1_000;

export interface RootKeyLifecycleConfig {
  /** Root-epoch validity from generation (default 3650 days). Rotation starts a
   *  fresh interval; successors are generated by administrator decision, not
   *  automatically, so the default must comfortably exceed operational reality. */
  lifetimeMs: number;
}

export const DEFAULT_ROOT_KEY_LIFETIME_MS = 3650 * 24 * 3_600_000;

function loadRootKeyLifecycle(): RootKeyLifecycleConfig {
  const lifetimeMs = loadPositiveMsInt(
    'SOMS_FEDERATION_ROOT_KEY_LIFETIME_MS',
    process.env.SOMS_FEDERATION_ROOT_KEY_LIFETIME_MS,
    DEFAULT_ROOT_KEY_LIFETIME_MS,
  );
  return { lifetimeMs };
}

function loadPositiveMsInt(
  name: string,
  raw: string | undefined,
  fallback: number,
): number {
  if (raw === undefined || raw === '') return fallback;
  const value = Number(raw);
  if (!Number.isSafeInteger(value) || value <= 0) {
    throw new Error(`${name} must be a positive integer (milliseconds)`);
  }
  return value;
}

/** Proactive refresh rounds run at least one second apart so a misconfigured tiny
 *  interval cannot turn peer certificate refresh into a request flood. */
function loadPeerKeyRefreshPollMs(): number {
  const value = loadPositiveMsInt(
    'SOMS_FEDERATION_KEY_REFRESH_POLL_MS',
    process.env.SOMS_FEDERATION_KEY_REFRESH_POLL_MS,
    DEFAULT_PEER_KEY_REFRESH_POLL_MS,
  );
  if (value < MIN_PEER_KEY_REFRESH_POLL_MS)
    throw new Error(
      `SOMS_FEDERATION_KEY_REFRESH_POLL_MS must be at least ${MIN_PEER_KEY_REFRESH_POLL_MS}ms`,
    );
  return value;
}

function loadSigningKeyLifecycle(): SigningKeyLifecycleConfig {
  const lifetimeMs = loadPositiveMsInt(
    'SOMS_FEDERATION_SIGNING_KEY_LIFETIME_MS',
    process.env.SOMS_FEDERATION_SIGNING_KEY_LIFETIME_MS,
    DEFAULT_SIGNING_KEY_LIFETIME_MS,
  );
  const clockSkewBudgetMs = loadPositiveMsInt(
    'SOMS_FEDERATION_CLOCK_SKEW_BUDGET_MS',
    process.env.SOMS_FEDERATION_CLOCK_SKEW_BUDGET_MS,
    DEFAULT_CLOCK_SKEW_BUDGET_MS,
  );
  const successorPrepublicationMs = loadPositiveMsInt(
    'SOMS_FEDERATION_SUCCESSOR_PREPUBLICATION_MS',
    process.env.SOMS_FEDERATION_SUCCESSOR_PREPUBLICATION_MS,
    DEFAULT_SUCCESSOR_PREPUBLICATION_MS,
  );
  const predecessorRetentionMs = loadPositiveMsInt(
    'SOMS_FEDERATION_PREDECESSOR_RETENTION_MS',
    process.env.SOMS_FEDERATION_PREDECESSOR_RETENTION_MS,
    DEFAULT_PREDECESSOR_RETENTION_MS,
  );
  if (successorPrepublicationMs < clockSkewBudgetMs) {
    throw new Error(
      'SOMS_FEDERATION_SUCCESSOR_PREPUBLICATION_MS must be at least SOMS_FEDERATION_CLOCK_SKEW_BUDGET_MS',
    );
  }
  if (predecessorRetentionMs < clockSkewBudgetMs) {
    throw new Error(
      'SOMS_FEDERATION_PREDECESSOR_RETENTION_MS must be at least SOMS_FEDERATION_CLOCK_SKEW_BUDGET_MS',
    );
  }
  if (
    lifetimeMs <=
    successorPrepublicationMs + predecessorRetentionMs + clockSkewBudgetMs
  ) {
    throw new Error(
      'SOMS_FEDERATION_SIGNING_KEY_LIFETIME_MS must exceed prepublication + retention + clock-skew budget',
    );
  }
  return {
    lifetimeMs,
    clockSkewBudgetMs,
    successorPrepublicationMs,
    predecessorRetentionMs,
  };
}

function loadForwardedResourcePolicy(): 'trust' | 'rebuild' {
  const value = process.env.SOMS_FEDERATION_FORWARDED_RESOURCE_POLICY;
  if (value === undefined || value === 'trust') return 'trust';
  if (value === 'rebuild') return 'rebuild';
  throw new Error(
    'SOMS_FEDERATION_FORWARDED_RESOURCE_POLICY must be trust or rebuild',
  );
}

export function loadFederationRuntimeConfig(): FederationRuntimeConfig {
  const allowInsecureHttp = process.env.SOMS_ALLOW_INSECURE_HTTP === '1';
  if (process.env.NODE_ENV === 'production' && allowInsecureHttp) {
    throw new Error(
      'SOMS_ALLOW_INSECURE_HTTP is forbidden when NODE_ENV=production',
    );
  }
  return {
    allowInsecureHttp,
    forwardedResourcePolicy: loadForwardedResourcePolicy(),
    signingKey: loadSigningKeyLifecycle(),
    rootKey: loadRootKeyLifecycle(),
    peerKeyRefreshPollMs: loadPeerKeyRefreshPollMs(),
  };
}

export function loadFederationConfig(): FederationConfig {
  const domain = requireEnv('SOMS_DOMAIN');
  if (!isValidSomfpDomain(domain)) {
    throw new Error('SOMS_DOMAIN must be a canonical SOMFP Domain');
  }
  return {
    domain,
    ...loadFederationRuntimeConfig(),
  };
}

/**
 * Federated-peer daily-quota configuration. These are the global defaults; a per-peer override on
 * Active IdentityNamespace overrides take precedence when set (null override -> use the default here). Thresholds
 * Loaded separately from FederationConfig to keep the
 * transport config focused. See src/quota/quota.service.ts.
 */
export interface QuotaConfig {
  /** Inbound relationship-intent entries/day per immutable namespace. */
  dailyRequestLimit: number;
  /** Messages/day per node. */
  dailyMsgLimit: number;
  /** Daily call budget per namespace: admitted invitation = 400, signaling frame = 1. */
  dailySignalLimit: number;
  /** File items/day per node for the file-cnt breaker dimension. All file types (image/video/audio/file) count
   *  +1; a forward bundle counts +1 regardless of inner asset count. */
  dailyFileLimit: number;
  /** Total file bytes/day per node for the file-total-size breaker dimension (uploads + downloads, actual
   *  bytes). Bundles contribute 0 bytes. */
  dailyFileBytesLimit: number;
}
